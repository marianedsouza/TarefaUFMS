"""### 3.3 Extraindo embeddings com DINOv2

Não faremos fine-tuning. O modelo será usado apenas como extrator de representação.
"""

import torch
from transformers import AutoImageProcessor, AutoModel

device = "cuda" if torch.cuda.is_available() else "cpu"
print("Device:", device)

image_model_name = "facebook/dinov2-small"
image_processor = AutoImageProcessor.from_pretrained(image_model_name)
image_model = AutoModel.from_pretrained(image_model_name).to(device)
image_model.eval()

def extract_image_embeddings(items, batch_size=16):
    embeddings = []
    labels = []

    for start in range(0, len(items), batch_size):
        batch = items[start:start+batch_size]
        images = [item["image"].convert("RGB") for item in batch]
        y = [item["labels"] for item in batch]

        inputs = image_processor(images=images, return_tensors="pt").to(device)

        with torch.no_grad():
            outputs = image_model(**inputs)
            emb = outputs.pooler_output

        embeddings.append(emb.cpu().numpy())
        labels.extend(y)

    return np.vstack(embeddings), np.array(labels)

X_img, y_img = extract_image_embeddings(selected)
