"""### 2.1 Outliers por IQR

> **Importante:** outlier estatístico não significa automaticamente erro.
"""

def iqr_outliers(series):
    s = series.dropna()
    q1, q3 = s.quantile([0.25, 0.75])
    iqr = q3 - q1
    lower = q1 - 1.5 * iqr
    upper = q3 + 1.5 * iqr
    return s[(s < lower) | (s > upper)]

print("Cenários atipicos que merecem atenção:\n")
